from launch import LaunchDescription
from launch_ros.actions import Node


def generate_launch_description():
    return LaunchDescription([
        Node(
            package='pillar_detector_pkg',
            executable='pillar_detector_node',
            name='pillar_detector',
            output='screen',
            parameters=[{
                # ────────────────────────────────────────────────
                # 话题
                # ────────────────────────────────────────────────
                # 雷达扫描话题名称
                'scan_topic': '/scan',

                # ────────────────────────────────────────────────
                # 柱子有效区域（单位：米）
                # 题目规定：柱子中心距场地边界 ≥50cm，场地 3×3m
                # 无人机在左下角(0,0)，向前(+x)向右(-y)
                # 所以柱子中心只可能在 x∈[0.5,2.5]，y∈[-2.5,-0.5]
                # ────────────────────────────────────────────────
                # 前方最近：距无人机起点 50cm
                'map_x_min_m': 0.5,
                # 前方最远：距前方边界 50cm
                'map_x_max_m': 2.5,
                # 右侧最远：距右侧边界 50cm（负数）
                'map_y_min_m': -2.5,
                # 右侧最近：距无人机起点 50cm（负数）
                'map_y_max_m': -0.5,

                # ────────────────────────────────────────────────
                # 柱子参数
                # ────────────────────────────────────────────────
                # 柱子正方形截面边长（米）
                # 用于根据距离自适应计算每帧该出现多少个激光点
                # 雷达精度 0.3°，1米处15cm柱子约打到29个点，3米处约10个点
                'pillar_width_m': 0.15,

                # 最多柱子数量（地图内固定4个，不可能更多）
                'max_pillars': 4,

                # ────────────────────────────────────────────────
                # 边沿检测参数
                # ────────────────────────────────────────────────
                # 判断柱子边沿的距离突变阈值（米）
                # 超过此值认为是进入或离开柱子的边沿
                'edge_threshold_m': 0.15,

                # 簇内最大点数上限（防止把墙误判为柱子）
                # 0.2米处15cm柱子约打到143个点，设70足够安全
                'max_cluster_pts': 70,

                # 柱面平整度容差（米）
                # 簇内最大距离与最小距离之差不超过此值，认为是平整的柱子面
                # 柱子与射线成45°时最大偏差约10cm，设20cm留有余量
                'stability_range_m': 0.20,

                # ────────────────────────────────────────────────
                # 多帧累积参数
                # ────────────────────────────────────────────────
                # 累积帧数（雷达15Hz，20帧约1.3秒）
                'accumulation_frames': 20,

                # 聚类合并距离（米）
                # 两次检测距离小于此值认为是同一个柱子
                'cluster_merge_dist_m': 0.20,

                # 最少投票帧数（20帧中至少12帧检测到才确认为柱子）
                # 60% 的帧检测到即可，留余量应对偶发遮挡
                'min_votes': 12,
            }],
        )
    ])
